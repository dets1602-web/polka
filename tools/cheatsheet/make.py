n = len(PAGES)
for i, (title, sub, blocks) in enumerate(PAGES, 1):
    im = Image.new("L", (W, H), 255)
    d = ImageDraw.Draw(im)
    y = M
    for ln in wrap(d, title, f_title, W - 2 * M):
        d.text((M, y), ln, font=f_title, fill=INK)
        y += lh(f_title)
    if sub:
        d.text((M, y), sub, font=f_sub, fill=GREY)
        y += lh(f_sub)
    y += 6
    d.rectangle([M, y, W - M, y + 3], fill=INK)
    y += 22
    for kind, text in blocks:
        if kind == "h":
            y += 8
            d.text((M, y), text, font=f_h, fill=INK)
            y += lh(f_h) + 2
        elif kind == "p":
            for ln in wrap(d, text, f_p, W - 2 * M):
                d.text((M, y), ln, font=f_p, fill=INK)
                y += lh(f_p)
            y += 6
        elif kind == "b":
            lines = wrap(d, text, f_b, W - 2 * M - 30)
            d.rectangle([M + 4, y + 12, M + 14, y + 22], fill=INK)
            for ln in lines:
                d.text((M + 30, y), ln, font=f_b, fill=INK)
                y += lh(f_b)
            y += 4
        elif kind in ("ex", "tip"):
            y += 8
            lines = wrap(d, text, f_b, W - 2 * M - 36)
            hgt = len(lines) * lh(f_b) + 24
            if kind == "tip":
                d.rectangle([M, y, W - M, y + hgt], fill=INK)
                col = 255
            else:
                d.rectangle([M, y, W - M, y + hgt], outline=INK, width=3)
                col = INK
            yy = y + 12
            for ln in lines:
                d.text((M + 18, yy), ln, font=f_b, fill=col)
                yy += lh(f_b)
            y += hgt + 10
    if y > H - 60:
        raise SystemExit(f"страница {i} не влезла: {y}")
    d.line([M, H - 52, W - M, H - 52], fill=INK, width=1)
